import { readFile, writeFile } from "node:fs/promises";
import { analyzeRecommendations } from "./analysis/backtest.mjs";

const root = new URL("../", import.meta.url);
const { draws } = JSON.parse(await readFile(new URL("data/lotto-data.json", root), "utf8"));
const { records } = JSON.parse(await readFile(new URL("data/weekly-recommendations.json", root), "utf8"));
const report = analyzeRecommendations({ draws, records });
const json = JSON.stringify(report, null, 2);
await writeFile(new URL("data/recommendation-analysis.json", root), `${json}\n`);
await writeFile(new URL("data/recommendation-analysis.js", root),
  `// Generated by scripts/analyze-recommendations.mjs\nexport const RECOMMENDATION_ANALYSIS = ${json};\n`);
console.log(`Analysis through draw ${report.latestDraw}: ${report.decision.status}`);
console.table(report.candidates.map(({ label, development, holdout, qualifies }) => ({
  strategy: label, developmentMean: development.averageHits.toFixed(3),
  holdoutMean: holdout.averageHits.toFixed(3), zeroPercent: (holdout.zeroHitRate * 100).toFixed(1),
  prizePercent: (holdout.prizeRate * 100).toFixed(2), adjustedP: holdout.adjustedPValue.toFixed(4), qualifies,
})));
console.log("Live performance:", report.live);
